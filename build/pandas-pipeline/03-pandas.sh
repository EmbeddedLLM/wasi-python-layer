#!/bin/bash
# Stage 3: build pandas 3.0.3 _libs for wasm32-wasip2 via the bypass (cythonize natively +
# cross-compile the .c). Compiles against the numpy 2.5.1 wasm install (stage 2) so the pandas
# .so match the runtime numpy C-API exactly. See design_docs/code_interpreter_wasm_pandas_build.md §6.
#
# Env: WASI_BUILD (default /tmp/wasi-build), PANDAS_VERSION (default 3.0.3).
# Produces: $WASI_BUILD/pandas/pandas-wasi/pandas (pure-python tree + wasm .so).
set -euo pipefail
export WASI_BUILD="${WASI_BUILD:-/tmp/wasi-build}"
PANDAS_VERSION="${PANDAS_VERSION:-3.0.3}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export HERE
HOSTPY="$WASI_BUILD/cpython-host/install/bin/python3.14"
export NUMPY_SITE="$WASI_BUILD/numpy251-install/usr/local/lib/python3.14/site-packages"
PD="$WASI_BUILD/pandas"
export PD_SRC="$PD/pandas-src"
export PD_OUT="$PD/pandas-wasi"
export PXi="$PD/pxi-out"
mkdir -p "$PD"

# --- fetch pandas sdist ---
if [ ! -d "$PD_SRC" ]; then
  echo ">>> downloading pandas $PANDAS_VERSION sdist"
  cd "$PD"
  URL="$(curl -fsSL "https://pypi.org/pypi/pandas/$PANDAS_VERSION/json" \
    | python3 -c "import json,sys; print([u['url'] for u in json.load(sys.stdin)['urls'] if u['url'].endswith('.tar.gz')][0])")"
  curl -fL "$URL" -o "pandas-$PANDAS_VERSION.tar.gz"
  tar xzf "pandas-$PANDAS_VERSION.tar.gz"
  mv "pandas-$PANDAS_VERSION" pandas-src
fi

# --- shared build venv (created in stage 1) has cython ---
export PATH="$WASI_BUILD/build-venv/bin:$PATH"
export CYTHON="$WASI_BUILD/build-venv/bin/cython"

# --- generate .pxi includes (Tempita) ---
echo ">>> generating .pxi includes"
mkdir -p "$PXi"
cd "$PD_SRC"
for f in pandas/_libs/*.pxi.in; do
  base="$(basename "$f" .pxi.in)"
  [ "$base" = "free_threading_config" ] && continue   # handled below (configure_file, not Tempita)
  "$WASI_BUILD/build-venv/bin/python" generate_pxi.py "$f" -o "$PXi"
done
# free_threading_config.pxi is a meson configure_file (not Tempita): Cython<3.1 -> not freethreading-compatible.
printf '# Autogenerated: Cython<3.1 -> not free-threading compatible\n\nDEF CYTHON_COMPATIBLE_WITH_FREE_THREADING = 0\n' > "$PXi/free_threading_config.pxi"

# --- patch pandas ctypes imports (no _ctypes on wasm) ---
"$HERE/patches/patch-pandas-ctypes.sh" "$PD_SRC"

# --- build all _libs extensions ---
echo ">>> building pandas _libs (bypass)"
"$WASI_BUILD/build-venv/bin/python" "$HERE/build_pandas_libs.py"

# --- copy the pure-python tree into the output package (the .so are already there) ---
echo ">>> assembling pandas package (pure-python + .so)"
cp -rn "$PD_SRC/pandas/." "$PD_OUT/pandas/" 2>/dev/null || cp -r "$PD_SRC/pandas/." "$PD_OUT/pandas/"
# re-apply ctypes patch on the assembled tree (cp may have brought unpatched files)
"$HERE/patches/patch-pandas-ctypes.sh" "$PD_OUT"

echo "=== Stage 3 done: pandas package at $PD_OUT/pandas ==="
find "$PD_OUT/pandas/_libs" -name "*.so" | wc -l
