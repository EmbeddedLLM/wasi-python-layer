#!/bin/bash
# Stage 4: assemble site-packages and verify in eryx.
set -euo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
export WASI_BUILD="${WASI_BUILD:-/tmp/wasi-build}"
MPL_BUILD="$WASI_BUILD/matplotlib-build"
MPL_SRC="$MPL_BUILD/matplotlib-3.11.1"
SITE="$MPL_BUILD/mpl-site"
WASI_STDLIB="$WASI_BUILD/cpython-wasi/install/lib/python3.14"

rm -rf "$SITE"
mkdir -p "$SITE"

# --- matplotlib pure-Python tree + .so files ---
echo ">>> Assembling matplotlib..."
cp -r "$MPL_SRC/lib/matplotlib" "$SITE/matplotlib"
cp "$MPL_BUILD/ext/_c_internal_utils.so" "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/ft2font.so"           "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/_path.so"             "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/_image.so"            "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/_qhull.so"            "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/_tri.so"              "$SITE/matplotlib/"
cp "$MPL_BUILD/ext/_backend_agg.so"      "$SITE/matplotlib/backends/"

# _version.py (normally generated by setuptools_scm)
cat > "$SITE/matplotlib/_version.py" << 'VEOF'
__version__ = "3.11.1"
version = __version__
version_tuple = (3, 11, 1)
VEOF

# --- contourpy ---
echo ">>> Assembling contourpy..."
cp -r "$MPL_BUILD/contourpy-1.3.2/lib/contourpy" "$SITE/contourpy"
cp "$MPL_BUILD/ext/_contourpy.so" "$SITE/contourpy/"

# --- kiwisolver (package with _cext.so) ---
echo ">>> Assembling kiwisolver..."
mkdir -p "$SITE/kiwisolver"
cp "$MPL_BUILD/kiwisolver-1.4.8/py/kiwisolver/"*.py "$SITE/kiwisolver/"
cp "$MPL_BUILD/ext/kiwisolver.so" "$SITE/kiwisolver/_cext.so"

# --- Pillow (from earlier pipeline) ---
echo ">>> Copying Pillow..."
if [ -d "$WASI_BUILD/pillow-out/PIL" ]; then
    cp -r "$WASI_BUILD/pillow-out/PIL" "$SITE/PIL"
elif [ -d "$WASI_BUILD/combined-site/PIL" ]; then
    cp -r "$WASI_BUILD/combined-site/PIL" "$SITE/PIL"
else
    echo "  WARNING: no wasm Pillow found; matplotlib.colors will fail on PIL import"
fi

# --- numpy (from pandas pipeline) ---
echo ">>> Copying numpy..."
cp -r "$WASI_BUILD/numpy251-install/usr/local/lib/python3.14/site-packages/numpy" "$SITE/"

# --- pandas (from pandas pipeline) ---
echo ">>> Copying pandas..."
if [ -d "$WASI_BUILD/combined-site/pandas" ]; then
    cp -r "$WASI_BUILD/combined-site/pandas" "$SITE/"
    cp -r "$WASI_BUILD/combined-site/pytz" "$SITE/" 2>/dev/null || true
    cp -r "$WASI_BUILD/combined-site/tzdata" "$SITE/" 2>/dev/null || true
else
    echo "  WARNING: no wasm pandas found in combined-site"
fi

# --- pure-Python deps ---
echo ">>> Fetching pure-Python deps..."
DEPS="$MPL_BUILD/pydeps-dl"; mkdir -p "$DEPS"
"$WASI_BUILD/build-venv/bin/pip" download --no-deps --only-binary :all: \
    cycler fonttools packaging pyparsing python-dateutil -d "$DEPS" >/dev/null 2>&1 || true
for whl in "$DEPS"/*.whl; do
    [ -f "$whl" ] || continue
    python3 -c "import zipfile; zipfile.ZipFile('$whl').extractall('$SITE')" 2>/dev/null
done
# six + dateutil from combined-site if available
cp "$WASI_BUILD/combined-site/six.py" "$SITE/" 2>/dev/null || true
cp -r "$WASI_BUILD/combined-site/dateutil" "$SITE/" 2>/dev/null || true
rm -rf "$SITE"/*.dist-info "$SITE"/*.data

# --- stdlib supplements (eryx's bundled stdlib is incomplete) ---
echo ">>> Copying stdlib supplements..."
cd "$WASI_STDLIB"
for item in *.py */; do
    base=$(basename "$item")
    case "$base" in
        site-packages|lib-dynload|test|idlelib|tkinter|turtledemo|turtle.py|ensurepip|venv|pydoc_data) continue ;;
    esac
    [ -e "$SITE/$base" ] || cp -r "$item" "$SITE/" 2>/dev/null || true
done

# --- sitecustomize.py (fix encodings for font manager) ---
cp "$HERE/sitecustomize.py" "$SITE/sitecustomize.py"

# --- mmap stub (no mmap on wasm) ---
cp "$WASI_BUILD/combined-site/mmap.py" "$SITE/mmap.py" 2>/dev/null || true

echo "=== Assembled site-packages at $SITE ==="
echo "  matplotlib .so: $(find "$SITE/matplotlib" -name '*.so' | wc -l) files"
echo "  total .py:      $(find "$SITE" -name '*.py' | wc -l) files"

# --- strip host-platform extensions (fonttools qu2cu etc.) before verifying ---
bash "$HERE/../strip-host-extensions.sh" "$SITE"

# --- verify in eryx ---
ERYX_PY="${ERYX_PY:-/tmp/eryx-probe/bin/python}"
if [ -x "$ERYX_PY" ]; then
    echo ">>> Verifying in eryx..."
    "$ERYX_PY" "$HERE/test_matplotlib.py" "$SITE"
else
    echo ">>> No eryx at $ERYX_PY; set ERYX_PY to verify."
fi
